/* ===== Cutting-stock solver (1D) — pure JS, no dependencies =====
   Column generation (revised simplex + bounded knapsack pricing) gives the LP lower bound,
   residual rounding builds an integer plan, then local repair tries to reach the bound. */
var Solver = (function () {
  "use strict";

  function makeRng(seed) {
    var s = (seed >>> 0) || 0x9e3779b9;
    return function () {
      s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0;
      return s / 4294967296;
    };
  }
  function now() { return (typeof performance !== "undefined" ? performance.now() : Date.now()); }
  function sum(a) { var t = 0; for (var i = 0; i < a.length; i++) t += a[i]; return t; }
  function key(a) { return a.join(","); }

  /* bounded knapsack: max sum v[i]*a[i]; sum w[i]*a[i] <= C; 0 <= a[i] <= ub[i] */
  function knapsack(v, w, ub, C) {
    var n = v.length, sub = [], i;
    for (i = 0; i < n; i++) {
      if (!(v[i] > 1e-12) || ub[i] <= 0) continue;
      var m = Math.min(ub[i], Math.floor(C / w[i])), k = 1;
      while (m > 0) { var t = Math.min(k, m); sub.push(i, t); m -= t; k *= 2; }
    }
    var S = sub.length / 2, best = new Float64Array(C + 1), take = new Array(S);
    for (var s = 0; s < S; s++) {
      var it = sub[2 * s], tt = sub[2 * s + 1], wt = w[it] * tt, val = v[it] * tt;
      var tk = new Uint8Array(C + 1);
      for (var c = C; c >= wt; c--) {
        var cand = best[c - wt] + val;
        if (cand > best[c] + 1e-12) { best[c] = cand; tk[c] = 1; }
      }
      take[s] = tk;
    }
    var a = new Array(n).fill(0), cap = C;
    for (s = S - 1; s >= 0; s--) {
      if (take[s][cap]) { var ii = sub[2 * s], q = sub[2 * s + 1]; a[ii] += q; cap -= w[ii] * q; }
    }
    return { value: best[C], a: a };
  }

  function invert(M) {
    var m = M.length, A = M.map(function (r, i) {
      var row = new Float64Array(2 * m); for (var j = 0; j < m; j++) row[j] = r[j]; row[m + i] = 1; return row;
    });
    for (var c = 0; c < m; c++) {
      var p = c, bv = Math.abs(A[c][c]);
      for (var r = c + 1; r < m; r++) if (Math.abs(A[r][c]) > bv) { bv = Math.abs(A[r][c]); p = r; }
      if (bv < 1e-12) return null;
      var tmp = A[c]; A[c] = A[p]; A[p] = tmp;
      var piv = A[c][c];
      for (var j = 0; j < 2 * m; j++) A[c][j] /= piv;
      for (r = 0; r < m; r++) if (r !== c) {
        var f = A[r][c]; if (f === 0) continue;
        for (j = 0; j < 2 * m; j++) A[r][j] -= f * A[c][j];
      }
    }
    return A.map(function (row) { return Float64Array.from(row.subarray(m)); });
  }

  /* LP: min sum x  s.t.  sum_j pool[j] x_j >= r, x >= 0.  Columns are generated by knapsack.
     pool: {list:[], map:Map}. Returns {z, x:[{j,val}], y}. */
  function solveLP(pool, r, w, C) {
    var m = r.length, i, j, k;
    function addCol(a) {
      var kk = key(a);
      if (pool.map.has(kk)) return pool.map.get(kk);
      pool.list.push(a); pool.map.set(kk, pool.list.length - 1); return pool.list.length - 1;
    }
    var basis = new Array(m), Binv = [], xB = new Float64Array(m);
    for (i = 0; i < m; i++) {
      var a = new Array(m).fill(0); a[i] = Math.min(r[i], Math.floor(C / w[i]));
      basis[i] = addCol(a);
      var row = new Float64Array(m); row[i] = 1 / a[i]; Binv.push(row);
      xB[i] = r[i] / a[i];
    }
    function col(jj) {
      if (jj >= 0) return pool.list[jj];
      var e = new Array(m).fill(0); e[-jj - 1] = -1; return e;
    }
    function refactor() {
      var M = [];
      for (var rr = 0; rr < m; rr++) M.push(new Float64Array(m));
      for (var cc = 0; cc < m; cc++) { var cv = col(basis[cc]); for (rr = 0; rr < m; rr++) M[rr][cc] = cv[rr]; }
      var inv = invert(M); if (!inv) return;
      Binv = inv;
      for (rr = 0; rr < m; rr++) { var s = 0; for (var t = 0; t < m; t++) s += Binv[rr][t] * r[t]; xB[rr] = Math.max(0, s); }
    }
    var y = new Float64Array(m), inBasis = new Set(basis), iter = 0, maxIter = 20000;
    while (iter++ < maxIter) {
      if (iter % 60 === 0) refactor();
      y.fill(0);
      for (i = 0; i < m; i++) if (basis[i] >= 0) { var bi = Binv[i]; for (k = 0; k < m; k++) y[k] += bi[k]; }
      var enter = null, bestRc = -1e-9;
      for (i = 0; i < m; i++) if (y[i] < bestRc && !inBasis.has(-(i + 1))) { bestRc = y[i]; enter = -(i + 1); }
      if (enter === null) {
        for (j = 0; j < pool.list.length; j++) {
          if (inBasis.has(j)) continue;
          var p = pool.list[j], d = 1;
          for (k = 0; k < m; k++) if (p[k]) d -= y[k] * p[k];
          if (d < bestRc) { bestRc = d; enter = j; }
        }
      }
      if (enter === null) {
        var vals = Array.from(y, function (v) { return v > 0 ? v : 0; });
        var ks = knapsack(vals, w, r, C);
        if (ks.value > 1 + 1e-9) {
          var jn = addCol(ks.a);
          if (inBasis.has(jn)) break;
          enter = jn;
        } else break;
      }
      var aq = col(enter), u = new Float64Array(m);
      for (i = 0; i < m; i++) { var s2 = 0, bi2 = Binv[i]; for (k = 0; k < m; k++) if (aq[k]) s2 += bi2[k] * aq[k]; u[i] = s2; }
      var pr = -1, th = Infinity;
      for (i = 0; i < m; i++) if (u[i] > 1e-9) {
        var ratio = xB[i] / u[i];
        if (ratio < th - 1e-12 || (Math.abs(ratio - th) <= 1e-12 && u[i] > u[pr])) { th = ratio; pr = i; }
      }
      if (pr < 0) break;
      var pivRow = Binv[pr], up = u[pr];
      for (k = 0; k < m; k++) pivRow[k] /= up;
      for (i = 0; i < m; i++) if (i !== pr && u[i] !== 0) {
        var bi3 = Binv[i], f = u[i];
        for (k = 0; k < m; k++) bi3[k] -= f * pivRow[k];
        xB[i] -= th * u[i]; if (xB[i] < 0) xB[i] = 0;
      }
      xB[pr] = th;
      inBasis.delete(basis[pr]); basis[pr] = enter; inBasis.add(enter);
    }
    var z = 0, x = [];
    for (i = 0; i < m; i++) if (basis[i] >= 0 && xB[i] > 1e-9) { z += xB[i]; x.push({ j: basis[i], val: xB[i] }); }
    return { z: z, x: x, y: y };
  }

  /* LP bound for demand d (full index space) */
  function lpBound(w, d, C, gpool) {
    var act = [], i;
    for (i = 0; i < d.length; i++) if (d[i] > 0) act.push(i);
    var pool = { list: [], map: new Map() };
    var res = solveLP(pool, act.map(function (i2) { return d[i2]; }), act.map(function (i2) { return w[i2]; }), C);
    pool.list.forEach(function (p) { addGlobal(gpool, expand(p, act, d.length)); });
    return res.z;
  }
  function expand(p, act, n) { var a = new Array(n).fill(0); for (var t = 0; t < act.length; t++) a[act[t]] = p[t]; return a; }
  function addGlobal(gpool, a) { var kk = key(a); if (!gpool.map.has(kk)) { gpool.map.set(kk, 1); gpool.list.push(a); } }

  /* residual rounding heuristic. returns array of bins (count vectors) */
  function residual(w, d, C, gpool, rng, randomize) {
    var n = d.length, r = d.slice(), bins = [], guard = 0;
    while (sum(r) > 0 && guard++ < 10000) {
      var act = [], i;
      for (i = 0; i < n; i++) if (r[i] > 0) act.push(i);
      var rA = act.map(function (i2) { return r[i2]; }), wA = act.map(function (i2) { return w[i2]; });
      var pool = { list: [], map: new Map() };
      gpool.list.forEach(function (p) {
        var q = act.map(function (i2) { return Math.min(p[i2], r[i2]); });
        if (sum(q) > 0) { var kk = key(q); if (!pool.map.has(kk)) { pool.list.push(q); pool.map.set(kk, pool.list.length - 1); } }
      });
      if (pool.list.length > 4000) { pool.list = pool.list.slice(-4000); pool.map = new Map(pool.list.map(function (q, t) { return [key(q), t]; })); }
      var res = solveLP(pool, rA, wA, C);
      pool.list.forEach(function (p) { addGlobal(gpool, expand(p, act, n)); });
      var picks = [];
      res.x.forEach(function (e) {
        var f = Math.floor(e.val + 1e-7);
        if (f > 0) picks.push({ p: expand(pool.list[e.j], act, n), f: f, frac: e.val - f });
      });
      var fr = res.x.filter(function (e) { return e.val - Math.floor(e.val + 1e-7) > 1e-7; });
      if (picks.length === 0 || (randomize && fr.length && rng() < 0.35)) {
        var chosen;
        if (randomize && fr.length) {
          var tot = 0; fr.forEach(function (e) { tot += e.val - Math.floor(e.val + 1e-7); });
          var t2 = rng() * tot; chosen = fr[0];
          for (var q2 = 0; q2 < fr.length; q2++) { t2 -= fr[q2].val - Math.floor(fr[q2].val + 1e-7); if (t2 <= 0) { chosen = fr[q2]; break; } }
        } else {
          chosen = res.x.reduce(function (a2, b2) { return b2.val > a2.val ? b2 : a2; });
        }
        picks.push({ p: expand(pool.list[chosen.j], act, n), f: 1, frac: 0 });
      }
      if (randomize) picks.sort(function () { return rng() - 0.5; });
      picks.forEach(function (pk) {
        for (var c = 0; c < pk.f; c++) {
          var q3 = pk.p.map(function (v, i3) { return Math.min(v, r[i3]); });
          if (sum(q3) === 0) break;
          bins.push(q3); for (var i4 = 0; i4 < n; i4++) r[i4] -= q3[i4];
        }
      });
    }
    return bins;
  }

  function binsToItems(bins) {
    return bins.map(function (b) { var it = []; b.forEach(function (c, i) { for (var t = 0; t < c; t++) it.push(i); }); return it; });
  }

  /* exact-ish DFS: pack item list into k bins of capacity C */
  function packDFS(items, w, k, C, nodeLimit) {
    items = items.slice().sort(function (a, b) { return w[b] - w[a] || a - b; });
    var caps = new Array(k).fill(C), assign = new Array(items.length), nodes = 0;
    var suffix = new Array(items.length + 1).fill(0);
    for (var t = items.length - 1; t >= 0; t--) suffix[t] = suffix[t + 1] + w[items[t]];
    function rec(idx) {
      if (idx === items.length) return true;
      if (++nodes > nodeLimit) return false;
      var capSum = 0; for (var b = 0; b < k; b++) capSum += caps[b];
      if (suffix[idx] > capSum) return false;
      var wt = w[items[idx]], tried = {};
      var startB = (idx > 0 && items[idx] === items[idx - 1]) ? assign[idx - 1] : 0;
      for (b = startB; b < k; b++) {
        if (caps[b] < wt || tried[caps[b]]) continue;
        tried[caps[b]] = 1; caps[b] -= wt; assign[idx] = b;
        if (rec(idx + 1)) return true;
        caps[b] += wt;
        if (nodes > nodeLimit) return false;
      }
      return false;
    }
    if (!rec(0)) return null;
    var out = []; for (var b2 = 0; b2 < k; b2++) out.push([]);
    items.forEach(function (it, t2) { out[assign[t2]].push(it); });
    return out;
  }

  /* try to drop bins by repacking a subset into one bin fewer */
  function repair(binsItems, w, C, LB, rng, deadline) {
    var bins = binsItems.map(function (b) { return b.slice(); });
    function load(b) { var s = 0; for (var t = 0; t < b.length; t++) s += w[b[t]]; return s; }
    var tries = 0;
    while (bins.length > LB && now() < deadline) {
      tries++;
      var order = bins.map(function (b, i) { return { i: i, waste: C - load(b) + rng() * C * 0.15 }; })
        .sort(function (a, b) { return b.waste - a.waste; });
      var S = [], waste = 0, t = 0;
      while (t < order.length && waste < C) { S.push(order[t].i); waste += C - load(bins[order[t].i]); t++; }
      if (waste < C) return bins;
      var extra = Math.floor(rng() * 4);
      var rest = order.slice(t).map(function (o) { return o.i; });
      for (var e = 0; e < extra && rest.length; e++) { var pick = Math.floor(rng() * rest.length); S.push(rest.splice(pick, 1)[0]); }
      var items = []; S.forEach(function (i) { items = items.concat(bins[i]); });
      var packed = packDFS(items, w, S.length - 1, C, 20000 + 2000 * items.length);
      if (packed) {
        var keep = bins.filter(function (b, i) { return S.indexOf(i) < 0; });
        bins = keep.concat(packed.filter(function (b) { return b.length > 0; }));
      }
      if (tries > 200000) break;
    }
    return bins;
  }

  /* main entry. lengths: array of piece lengths (distinct), demand: counts. */
  function solve(lengths, demand, stock, kerf, opts) {
    opts = opts || {};
    var timeBudget = opts.timeMs != null ? opts.timeMs : 6000;
    var t0 = now();
    var n = lengths.length, i;
    var idx = lengths.map(function (l, i2) { return i2; }).sort(function (a, b) { return lengths[b] - lengths[a]; });
    var L = idx.map(function (i2) { return lengths[i2]; }), d = idx.map(function (i2) { return demand[i2]; });
    var C = Math.round(stock);
    for (i = 0; i < n; i++) if (L[i] > C) return { error: "Деталь " + L[i] + " мм длиннее штанги " + C + " мм" };
    var w = L.map(function (l) { return Math.min(Math.round(l + kerf), C); });
    var gpool = { list: [], map: new Map() };
    var z = lpBound(w, d, C, gpool);
    var LB = Math.max(1, Math.ceil(z - 1e-6));
    var rng = makeRng(opts.seed || 12345);
    var best = binsToItems(residual(w, d, C, gpool, rng, false));
    var deadline = t0 + timeBudget, rounds = 0;
    if (best.length > LB) best = repair(best, w, C, LB, rng, Math.min(deadline, now() + timeBudget * 0.25));
    while (best.length > LB && now() < deadline) {
      rounds++;
      var cand = binsToItems(residual(w, d, C, gpool, rng, true));
      if (cand.length > LB) cand = repair(cand, w, C, LB, rng, Math.min(deadline, now() + 400));
      if (cand.length < best.length) best = cand;
    }
    // group identical bins into patterns
    var groups = new Map();
    best.forEach(function (b) {
      var items = b.map(function (it) { return L[it]; }).sort(function (a, c) { return c - a; });
      var kk = items.join(",");
      if (!groups.has(kk)) groups.set(kk, { items: items, count: 0 });
      groups.get(kk).count++;
    });
    var patterns = Array.from(groups.values()).map(function (g) {
      var used = sum(g.items) + kerf * g.items.length;
      return { items: g.items, count: g.count, rest: C - used };
    }).sort(function (a, b) { return a.rest - b.rest || b.count - a.count; });
    // verification
    var got = new Map();
    patterns.forEach(function (p) { p.items.forEach(function (l) { got.set(l, (got.get(l) || 0) + p.count); }); });
    for (i = 0; i < n; i++) if (got.get(L[i]) !== d[i]) return { error: "Внутренняя ошибка проверки комплектности" };
    patterns.forEach(function (p) { if (p.items.reduce(function (s, l) { return s + Math.min(l + kerf, C); }, 0) > C) throw new Error("overfull"); });
    return {
      bars: best.length, lb: LB, lp: z, optimal: best.length === LB, patterns: patterns,
      pieces: sum(d), totalLength: L.reduce(function (s, l, i2) { return s + l * d[i2]; }, 0),
      ms: Math.round(now() - t0), rounds: rounds
    };
  }

  return { solve: solve, knapsack: knapsack, makeRng: makeRng };
})();

if (typeof module !== "undefined" && module.exports) module.exports = Solver;
if (typeof window === "undefined" && typeof self !== "undefined" && typeof importScripts === "function") {
  self.onmessage = function (ev) {
    var msg = ev.data, out;
    try { out = Solver.solve(msg.lengths, msg.demand, msg.stock, msg.kerf, msg.opts); }
    catch (e) { out = { error: String(e && e.message || e) }; }
    self.postMessage({ id: msg.id, result: out });
  };
}
